@register.simple_tag
def icon(name, size=20, cls='', stroke=2.2):
    body = ICONS.get(name, '')
    return mark_safe(
        f'<svg class="ic {cls}" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true">{body}</svg>'
    )


def _to_float(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


@register.filter
def risk_tier(value):
    """Risk tier for a 0..1 probability: low, mid or high."""
    v = _to_float(value)
    if v is None:
        return ''
    if v >= 0.7:
        return 'high'
    if v >= 0.3:
        return 'mid'
    return 'low'


@register.filter
def risk_tier_pct(value):
    """Risk tier for a 0..100 percentage."""
    v = _to_float(value)
    if v is None:
        return ''
    return risk_tier(v / 100)


@register.filter
def risk_label(tier):
    return {'high': 'Yuqori', 'mid': "O'rta", 'low': 'Past'}.get(tier, '')


@register.filter
def initial(name):
    name = (name or '').strip()
    return name[:1].upper() if name else '?'


@register.filter
def norm_flag(value, bounds):
    """Compare a measurement with a normal range "low,high": returns low, high or ok."""
    v = _to_float(value)
    if v is None:
        return ''
    low, high = (float(x) for x in bounds.split(','))
    if v > high:
        return 'high'
    if v < low:
        return 'low'
    return 'ok'


@register.filter
def split(value, sep=None):
    return str(value).split(sep)


@register.filter
def gender(value):
    return {'E': 'Erkak', 'A': 'Ayol', 1: 'Erkak', 0: 'Ayol'}.get(value, value)


@register.filter
def clamp_pct(value):
    """Clamp a number to 0..100 for CSS widths.

    Returned as a string so the Uzbek locale does not turn 20.5 into "20,5",
    which would be invalid CSS.
    """
    v = _to_float(value)
    if v is None:
        return '0'
    return f'{max(0.0, min(100.0, v)):.1f}'


@register.simple_tag(takes_context=True)
def qs(context, key, value=''):
    """Current query string with one parameter replaced (or removed when empty)."""
    params = context['request'].GET.copy()
    params.pop('page', None)
    if value in ('', None):
        params.pop(key, None)
    else:
        params[key] = value
    encoded = params.urlencode()
    return '?' + encoded if encoded else '?'


@register.simple_tag
def nav_stats():
    """Small counters for the sidebar: today's open visits and high no-show risks ahead."""
    from patients.models import Appointment

    today = timezone.now().date()
    scheduled = Appointment.objects.filter(holat='rejalashtirilgan')
    return {
        'today': scheduled.filter(uchrashuv_sanasi__date=today).count(),
        'alerts': scheduled.filter(uchrashuv_sanasi__date__gte=today, kelmay_qolish_riski__gte=0.7).count(),
    }
